const esc = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

let enriched = 0;
for (const [slug, addition] of Object.entries(additions)) {
  const path = join(learnDir, `${slug}.html`);
  let html = await readFile(path, 'utf8');
  if (html.includes('data-finkit-article-expansion="reviewed"')) continue;
  const marker = '      <section class="panel">\n        <h2>檢查清單</h2>';
  if (!html.includes(marker)) throw new Error(`Could not find checklist insertion point for ${slug}`);
  const block = `      <section data-finkit-article-expansion="reviewed">\n        <h2>${esc(addition.title)}</h2>\n        ${addition.paragraphs.map((paragraph) => `<p>${esc(paragraph)}</p>`).join('\n        ')}\n      </section>\n`;
  html = html.replace(marker, `${block}${marker}`);
  await writeFile(path, html);
  enriched += 1;
}

console.log(`Learning article enrichment complete: ${enriched} articles expanded with curated decision guidance`);
