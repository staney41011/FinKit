const escapeHtml = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

const renderEditorial = (item) => `
      <section data-finkit-editorial="reviewed" class="publisher-content">
        <h2>怎麼使用這個工具，才不會只看一個數字</h2>
        <p>${escapeHtml(item.summary)}</p>
        <h3>建議操作順序</h3>
        <ol>${item.steps.map((step) => `<li>${escapeHtml(step)}</li>`).join('')}</ol>
        <h3>情境例子</h3>
        <p>${escapeHtml(item.example)}</p>
        <h3>結果應該怎麼判讀</h3>
        ${item.interpretation.map((paragraph) => `<p>${escapeHtml(paragraph)}</p>`).join('')}
        <h3>常見誤區</h3>
        <ul>${item.mistakes.map((mistake) => `<li>${escapeHtml(mistake)}</li>`).join('')}</ul>
      </section>`;

let enriched = 0;
for (const [slug, item] of Object.entries(editorials)) {
  const path = join(toolsDir, `${slug}.html`);
  let html;
  try {
    html = await readFile(path, 'utf8');
  } catch {
    throw new Error(`Missing generated tool page for curated content: ${slug}`);
  }
  if (html.includes('data-finkit-editorial="reviewed"')) continue;
  const marker = '      <section>\n        <h2>常見問題</h2>';
  if (!html.includes(marker)) throw new Error(`Could not locate FAQ insertion point for ${slug}`);
  html = html.replace(marker, `${renderEditorial(item)}\n${marker}`);
  html = html.replace('</style>', '\n      .publisher-content{margin-top:34px;background:#fff;border:1px solid #e2e8f0;border-radius:12px;padding:24px}.publisher-content h3{margin-top:24px}.publisher-content li{margin:8px 0;color:#475569}.publisher-content p{color:#475569}\n    </style>');
  await writeFile(path, html);
  enriched += 1;
}

console.log(`Curated publisher-content enrichment complete: ${enriched} tool pages enriched`);
